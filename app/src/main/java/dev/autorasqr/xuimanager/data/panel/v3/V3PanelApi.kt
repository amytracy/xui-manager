internal class V3PanelApi(
    private val service: V3PanelService,
    private val json: Json,
) : PanelApi {

    override val capabilities = PanelCapabilities(multiInboundClients = true, realityScan = true, routing = true, nodes = true, selfUpdate = true, xrayInstall = true)

    override suspend fun status(): PanelStatus {
        val dto = PanelJson.decode<V3Status>(json, call { service.status() })
        return PanelStatus(
            cpuPercent = dto.cpu,
            memUsed = dto.mem.current,
            memTotal = dto.mem.total,
            uptimeSeconds = dto.uptime,
            loads = dto.loads,
            xrayState = dto.xray.state,
            xrayVersion = dto.xray.version,
            xrayError = dto.xray.errorMsg,
            panelVersion = dto.panelVersion,
        )
    }

    override suspend fun listClients(): List<PanelClient> =
        PanelJson.decode<List<V3ClientRow>?>(json, call { service.clients() }).orEmpty().map { row ->
            PanelClient(
                email = row.email,
                enabled = row.enable,
                subId = row.subId,
                totalBytes = row.totalGB,
                expiryTime = row.expiryTime,
                up = row.traffic?.up ?: 0,
                down = row.traffic?.down ?: 0,
                inboundIds = row.inboundIds.orEmpty(),
                comment = row.comment,
            )
        }

    override suspend fun onlineEmails(): Set<String> =
        PanelJson.decode<List<String>?>(json, call { service.onlines() }).orEmpty().toSet()

    /** Per-protocol secrets (UUID, Trojan password, SS key) are generated by the panel when omitted. */
    override suspend fun addClient(client: NewClient) {
        val body = buildJsonObject {
            putJsonObject("client") {
                put("email", client.email)
                put("subId", client.subId)
                put("totalGB", client.totalBytes)
                put("expiryTime", client.expiryTime)
                put("enable", client.enabled)
                put("flow", client.flow)
                put("limitIp", 0)
                put("tgId", 0)
                put("comment", "")
            }
            putJsonArray("inboundIds") { client.inboundIds.forEach { add(JsonPrimitive(it)) } }
        }
        call { service.addClient(body) }
    }

    override suspend fun updateClient(email: String, changes: ClientChanges) {
        val current = PanelJson.objectOrNull(json, call { service.client(email) })
            ?: throw AppException(AppError.PanelError("client not found"))
        val record = current["client"] as? JsonObject ?: throw AppException(AppError.PanelError("client not found"))
        val attached = (current["inboundIds"] as? JsonArray).orEmpty().mapNotNull { it.jsonPrimitive.intOrNull }.toSet()

        call { service.updateClient(email, V3ClientPayload.update(record, changes)) }

        val wanted = changes.inboundIds.toSet()
        val toAttach = wanted - attached
        val toDetach = attached - wanted
        if (toAttach.isNotEmpty()) call { service.attach(changes.email, inboundIds(toAttach)) }
        if (toDetach.isNotEmpty()) call { service.detach(changes.email, inboundIds(toDetach)) }
    }

    override suspend fun deleteClient(email: String) {
        call { service.deleteClient(email) }
    }

    override suspend fun setClientEnabled(email: String, enabled: Boolean) {
        val body = buildJsonObject { putJsonArray("emails") { add(JsonPrimitive(email)) } }
        val result = call { if (enabled) service.bulkEnable(body) else service.bulkDisable(body) }
        val skipped = PanelJson.decode<V3BulkResult?>(json, result)?.skipped.orEmpty()
        skipped.firstOrNull { it.email == email }?.let { throw AppException(AppError.PanelError(it.reason.ifBlank { "skipped" })) }
    }

    override suspend fun resetClientTraffic(email: String) {
        call { service.resetTraffic(email) }
    }

    override suspend fun listInbounds(): List<PanelInbound> =
        (call { service.inbounds() } as? JsonArray).orEmpty().mapNotNull { (it as? JsonObject)?.let { raw -> InboundJson.summary(json, raw) } }

    override suspend fun getInbound(id: Int): JsonObject =
        PanelJson.objectOrNull(json, call { service.inbound(id) })?.let { InboundJson.normalize(json, it) }
            ?: throw AppException(AppError.PanelError("inbound $id not found"))

    override suspend fun updateInbound(id: Int, inbound: JsonObject) {
        call { service.updateInbound(id, InboundJson.normalize(json, inbound)) }
    }

    override suspend fun deleteInbound(id: Int) {
        call { service.deleteInbound(id) }
    }

    override suspend fun setInboundEnabled(id: Int, enabled: Boolean) {
        call { service.setInboundEnable(id, buildJsonObject { put("enable", enabled) }) }
    }

    override suspend fun addInbound(spec: InboundSpec): Int {
        val body = buildJsonObject {
            put("enable", true)
            put("remark", spec.remark)
            put("listen", "")
            put("port", spec.port)
            put("protocol", InboundJson.protocolName(spec.protocol))
            put("expiryTime", 0)
            put("total", 0)
            put("settings", InboundJson.settings(spec))
            put("streamSettings", InboundJson.streamSettings(spec))
            put("sniffing", InboundJson.sniffing())
            spec.nodeId?.let {
                put("nodeId", it)
                put("shareAddrStrategy", "node")
            }
        }
        val created = PanelJson.objectOrNull(json, call { service.addInbound(body) })
        return created?.int("id")
            ?: listInbounds().firstOrNull { it.remark == spec.remark && it.port == spec.port }?.id
            ?: throw AppException(AppError.PanelError("inbound was not created"))
    }

    override suspend fun subscriptionSettings(): SubscriptionSettings =
        subscriptionFrom(allSettings())

    /** /setting/update replaces the whole settings blob, so read it, patch the subscription fields and write it back. */
    override suspend fun updateSubscriptionSettings(update: SubscriptionUpdate) {
        call { service.updateSettings(patchSubscription(allSettings(), update)) }
    }

    override suspend fun settings(): JsonObject = allSettings()

    override suspend fun patchSettings(changes: Map<String, JsonElement>) {
        call { service.updateSettings(JsonObject(allSettings() + changes)) }
    }

    override suspend fun xrayTemplate(): XrayTemplate {
        val wrapper = PanelJson.objectOrNull(json, call { service.xraySetting() })
            ?: throw AppException(AppError.PanelError("empty Xray settings"))
        val config = PanelJson.objectOrNull(json, wrapper["xraySetting"])
            ?: throw AppException(AppError.PanelError("Xray template is not a JSON object"))
        return XrayTemplate(config, wrapper.string("outboundTestUrl").orEmpty())
    }

    override suspend fun saveXrayTemplate(template: XrayTemplate) {
        call { service.updateXraySetting(template.config.toString(), template.outboundTestUrl) }
    }

    override suspend fun restartPanel() {
        call { service.restartPanel() }
    }

    override suspend fun restartXray() {
        call { service.restartXray() }
    }

    override suspend fun newX25519(): X25519Keys {
        val dto = PanelJson.decode<V3X25519>(json, call { service.newX25519() })
        if (dto.privateKey.isBlank() || dto.publicKey.isBlank()) throw AppException(AppError.PanelError("empty x25519 keypair"))
        return X25519Keys(dto.privateKey, dto.publicKey)
    }

    override suspend fun scanRealityTargets(candidates: List<String>): List<RealityTargetVerdict> =
        PanelJson.decode<List<V3RealityVerdict>?>(json, call { service.scanRealityTargets(candidates.joinToString(",")) })
            .orEmpty()
            .map { RealityTargetVerdict(it.target, it.host, it.feasible, it.latencyMs) }

    override suspend fun addInboundRaw(inbound: JsonObject): Int {
        val body = InboundJson.normalize(json, inbound)
        val created = PanelJson.objectOrNull(json, call { service.addInbound(body) })
        return created?.int("id")
            ?: listInbounds().firstOrNull { it.port == body.int("port") && it.remark == body.string("remark").orEmpty() }?.id
            ?: throw AppException(AppError.PanelError("inbound was not created"))
    }

    override suspend fun newMldsa65(): Pair<String, String> {
        val obj = PanelJson.objectOrNull(json, call { service.newMldsa65() }) ?: throw AppException(AppError.PanelError("empty ML-DSA-65 key"))
        return obj.string("seed").orEmpty() to obj.string("verify").orEmpty()
    }

    override suspend fun newVlessEncAuths(): List<VlessEncAuth> {
        val obj = PanelJson.objectOrNull(json, call { service.newVlessEnc() })
        return (obj?.get("auths") as? JsonArray).orEmpty().mapNotNull { it as? JsonObject }.map {
            VlessEncAuth(it.string("id").orEmpty(), it.string("label").orEmpty(), it.string("decryption").orEmpty(), it.string("encryption").orEmpty())
        }
    }

    override suspend fun scanRealityTarget(target: String, sni: String, xver: Int, allowPrivate: Boolean): JsonObject =
        PanelJson.objectOrNull(json, call { service.scanRealityTarget(target, sni, xver, allowPrivate) })
            ?: throw AppException(AppError.PanelError("empty scan result"))

    override suspend fun newEchCert(sni: String): Pair<String, String> {
        val obj = PanelJson.objectOrNull(json, call { service.newEchCert(sni) }) ?: throw AppException(AppError.PanelError("empty ECH certificate"))
        return obj.string("echServerKeys").orEmpty() to obj.string("echConfigList").orEmpty()
    }

    override suspend fun certHash(certFile: String, certContent: String): List<String> =
        (call { service.certHash(certFile, certContent) } as? JsonArray).orEmpty().mapNotNull { (it as? JsonPrimitive)?.content }

    override suspend fun remoteCertHash(server: String, allowPrivate: Boolean): List<String> =
        (call { service.remoteCertHash(server, allowPrivate) } as? JsonArray).orEmpty().mapNotNull { (it as? JsonPrimitive)?.content }

    override suspend fun fallbacks(masterId: Int): List<JsonObject> =
        (call { service.fallbacks(masterId) } as? JsonArray).orEmpty().mapNotNull { it as? JsonObject }

    override suspend fun setFallbacks(masterId: Int, fallbacks: List<JsonObject>) {
        call { service.setFallbacks(masterId, JsonObject(mapOf("fallbacks" to JsonArray(fallbacks)))) }
    }

    override suspend fun listNodes(): List<PanelNode> =
        PanelJson.decode<List<V3Node>?>(json, call { service.nodes() }).orEmpty().map { it.toModel() }

    override suspend fun addNode(node: NodeMutation): Int {
        val created = PanelJson.objectOrNull(json, call { service.addNode(nodeBody(node)) })
        return created?.int("id")
            ?: listNodes().firstOrNull { it.name == node.name.trim() }?.id
            ?: throw AppException(AppError.PanelError("node was not created"))
    }

    override suspend fun updateNode(id: Int, node: NodeMutation) {
        call { service.updateNode(id, nodeBody(node.copy(id = id))) }
    }

    override suspend fun deleteNode(id: Int) {
        call { service.deleteNode(id) }
    }

    override suspend fun setNodeEnabled(id: Int, enabled: Boolean) {
        call { service.setNodeEnable(id, buildJsonObject { put("enable", enabled) }) }
    }

    override suspend fun probeNode(id: Int): NodeProbe =
        PanelJson.decode<V3NodeProbe?>(json, call { service.probeNode(id) })?.toModel()
            ?: throw AppException(AppError.PanelError("empty probe result"))

    override suspend fun testNode(node: NodeMutation): NodeProbe =
        PanelJson.decode<V3NodeProbe?>(json, call { service.testNode(nodeBody(node)) })?.toModel()
            ?: throw AppException(AppError.PanelError("empty probe result"))

    override suspend fun nodeCertFingerprint(node: NodeMutation): String =
        (call { service.nodeCertFingerprint(nodeBody(node)) } as? JsonPrimitive)?.content?.takeIf { it.isNotBlank() }
            ?: throw AppException(AppError.PanelError("empty certificate fingerprint"))

    override suspend fun nodeRemoteInbounds(node: NodeMutation): List<RemoteInboundOption> =
        PanelJson.decode<List<V3RemoteInbound>?>(json, call { service.nodeInbounds(nodeBody(node)) }).orEmpty()
            .filter { it.tag.isNotBlank() }
            .map { RemoteInboundOption(it.tag, it.remark, it.protocol, it.port) }

    override suspend fun nodeWebCert(id: Int): Pair<String, String>? {
        val obj = PanelJson.objectOrNull(json, call { service.nodeWebCert(id) }) ?: return null
        val cert = obj.string("webCertFile").orEmpty()
        val key = obj.string("webKeyFile").orEmpty()
        return if (cert.isBlank() || key.isBlank()) null else cert to key
    }

    override suspend fun updateNodePanels(ids: List<Int>): List<NodeUpdateResult> {
        val body = buildJsonObject {
            putJsonArray("ids") { ids.forEach { add(JsonPrimitive(it)) } }
            put("dev", false)
        }
        return PanelJson.decode<List<V3NodeUpdateResult>?>(json, call { service.updateNodePanels(body) }).orEmpty()
            .map { NodeUpdateResult(it.id, it.name, it.ok, it.error) }
    }

    override suspend fun panelUpdateInfo(): PanelUpdateInfo {
        val dto = PanelJson.decode<V3PanelUpdateInfo?>(json, call { service.panelUpdateInfo() })
            ?: throw AppException(AppError.PanelError("empty update info"))
        return PanelUpdateInfo(dto.currentVersion, dto.latestVersion, dto.updateAvailable)
    }

    override suspend fun startPanelUpdate(): String =
        PanelJson.objectOrNull(json, call { service.updatePanel() })?.string("runId")?.takeIf { it.isNotBlank() }
            ?: throw AppException(AppError.PanelError("the panel did not start the update"))

    override suspend fun panelUpdateStatus(): PanelUpdateRun {
        val dto = PanelJson.decode<V3PanelUpdateStatus?>(json, call { service.updateStatus() }) ?: V3PanelUpdateStatus()
        return PanelUpdateRun(dto.runId, dto.state.ifBlank { "pending" }, dto.exitCode)
    }

    override suspend fun xrayVersions(): List<String> =
        PanelJson.decode<List<String>?>(json, call { service.xrayVersions() }).orEmpty()

    override suspend fun installXray(version: String) {
        call { service.installXray(version) }
    }

    private suspend fun allSettings(): JsonObject =
        PanelJson.objectOrNull(json, call { service.allSettings() }) ?: throw AppException(AppError.PanelError("empty settings"))

    private suspend fun call(request: suspend () -> ResponseBody): JsonElement? =
        PanelJson.unwrap(json, request().use { it.string() })

    private fun inboundIds(ids: Set<Int>) = buildJsonObject { putJsonArray("inboundIds") { ids.sorted().forEach { add(JsonPrimitive(it)) } } }

    companion object {
        /** Same rules as the panel's NodeFormModal: plain http never verifies, pins and tags only where they apply. */
        internal fun nodeBody(node: NodeMutation) = buildJsonObject {
            val http = node.scheme == "http"
            val tls = if (http) "skip" else node.tlsVerifyMode
            put("id", node.id)
            put("name", node.name.trim())
            put("remark", node.remark.trim())
            put("scheme", if (http) "http" else "https")
            put("address", node.address.trim())
            put("port", node.port)
            put("basePath", node.basePath.trim().ifEmpty { "/" })
            put("enable", node.enabled)
            put("allowPrivateAddress", node.allowPrivateAddress)
            put("tlsVerifyMode", tls)
            put("pinnedCertSha256", if (tls == "pin") node.pinnedCertSha256.trim() else "")
            put("inboundSyncMode", node.inboundSyncMode)
            putJsonArray("inboundTags") {
                if (node.inboundSyncMode == "selected") node.inboundTags.forEach { add(JsonPrimitive(it)) }
            }
            put("outboundTag", node.outboundTag)
            node.apiToken?.trim()?.takeIf { it.isNotEmpty() }?.let { put("apiToken", it) }
        }

        private fun V3Node.toModel() = PanelNode(
            id = id, name = name, remark = remark, scheme = scheme, address = address, port = port, basePath = basePath,
            enabled = enable, status = status.ifBlank { "unknown" }, latencyMs = latencyMs, cpuPercent = cpuPct,
            memPercent = memPct, uptimeSeconds = uptimeSecs, xrayState = xrayState, xrayVersion = xrayVersion,
            xrayError = xrayError, panelVersion = panelVersion, lastError = lastError, lastHeartbeat = lastHeartbeat,
            inboundCount = inboundCount, clientCount = clientCount, onlineCount = onlineCount, hasApiToken = hasApiToken,
            tlsVerifyMode = tlsVerifyMode, pinnedCertSha256 = pinnedCertSha256, inboundSyncMode = inboundSyncMode,
            inboundTags = inboundTags.orEmpty(), outboundTag = outboundTag, allowPrivateAddress = allowPrivateAddress,
            transitive = transitive,
        )

        private fun V3NodeProbe.toModel() = NodeProbe(
            online = status == "online", error = error, latencyMs = latencyMs, cpuPercent = cpuPct, memPercent = memPct,
            uptimeSeconds = uptimeSecs, xrayState = xrayState, xrayVersion = xrayVersion, xrayError = xrayError,
            panelVersion = panelVersion,
        )

        internal fun subscriptionFrom(all: JsonObject) = SubscriptionSettings(
            enabled = all.bool("subEnable") ?: false,
            port = all.int("subPort") ?: 2096,
            path = all.string("subPath") ?: "/sub/",
            domain = all.string("subDomain").orEmpty(),
            certFile = all.string("subCertFile").orEmpty(),
            keyFile = all.string("subKeyFile").orEmpty(),
            uri = all.string("subURI").orEmpty(),
        )

        internal fun patchSubscription(all: JsonObject, update: SubscriptionUpdate) = JsonObject(
            all.toMutableMap().apply {
                put("subEnable", JsonPrimitive(update.enabled))
                update.port?.let { put("subPort", JsonPrimitive(it)) }
                update.path?.let { put("subPath", JsonPrimitive(it)) }
                update.certFile?.let { put("subCertFile", JsonPrimitive(it)) }
                update.keyFile?.let { put("subKeyFile", JsonPrimitive(it)) }
            },
        )
    }
}
