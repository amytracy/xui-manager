/** The inbound to create, before keys and paths are filled in. */
data class InboundRequest(
    val remark: String,
    val protocol: InboundProtocol,
    val transport: InboundTransport,
    val port: Int,
    /** Reality target chosen by the user, or null for automatic choice. Ignored with [selfSteal]. */
    val sni: String?,
    val fingerprint: String,
    /** Reality borrows the server's own site: target is the local decoy site, SNI is the domain. */
    val selfSteal: SelfStealTarget? = null,
    /** Node to host the inbound on (3x-ui v3). */
    val nodeId: Int? = null,
)

data class SelfStealTarget(val domain: String, val localPort: Int) {
    val target: String get() = "127.0.0.1:$localPort"
}

class CreatedInbound(val id: Int, val serverName: String?, val targetVerified: Boolean)

/** Creates inbounds in the shape 3x-ui's own form produces; used by the deploy and by the inbounds screen. */
@Singleton
class InboundFactory @Inject constructor(private val random: RandomTokens) {

    /**
     * [scanner] probes Reality targets; it is the panel on the server that will host the inbound when the app can
     * reach it (a node's own panel), otherwise [api].
     */
    suspend fun create(
        api: PanelApi,
        request: InboundRequest,
        serverKeys: X25519Keys?,
        scanner: PanelApi = api,
        log: (String) -> Unit,
    ): CreatedInbound {
        var verified = true
        val reality = if (InboundMatrix.security(request.protocol) == InboundSecurity.REALITY) {
            val keys = serverKeys ?: api.newX25519().also { log("Reality key pair generated by the panel") }
            val selfSteal = request.selfSteal
            val (target, serverName) = if (selfSteal != null) {
                selfSteal.target to selfSteal.domain
            } else {
                val (host, ok) = chooseTarget(scanner, request.sni, log)
                verified = ok
                "$host:443" to host
            }
            RealityParams(
                target = target,
                serverName = serverName,
                privateKey = keys.privateKey,
                publicKey = keys.publicKey,
                shortId = random.hex(8),
                fingerprint = request.fingerprint,
            )
        } else {
            null
        }
        val spec = InboundSpec(
            remark = request.remark,
            port = request.port,
            protocol = request.protocol,
            transport = request.transport,
            reality = reality,
            path = when (request.transport) {
                InboundTransport.WS, InboundTransport.XHTTP -> "/" + random.lowerAlphanumeric(12)
                InboundTransport.GRPC -> random.lowerAlphanumeric(12)
                InboundTransport.TCP -> ""
            },
            shadowsocksPassword = if (request.protocol == InboundProtocol.SHADOWSOCKS) random.base64Key(32) else null,
            nodeId = request.nodeId,
        )
        log("Creating ${spec.protocol} over ${spec.transport} inbound on port ${spec.port}" + (spec.nodeId?.let { " on node #$it" } ?: "") + (reality?.let { ", target ${it.target}, SNI ${it.serverName}" } ?: ""))
        return CreatedInbound(api.addInbound(spec), reality?.serverName, verified)
    }

    /** Asks the panel to probe [candidates] from the server (v3 only); empty if it cannot. */
    suspend fun scan(api: PanelApi, candidates: List<String>, log: (String) -> Unit): List<RealityTargetVerdict> {
        if (!api.capabilities.realityScan) return emptyList()
        return try {
            api.scanRealityTargets(candidates)
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            log("Target scan failed: ${e.toAppError()}")
            emptyList()
        }
    }

    /** Returns the chosen host and whether the panel's scanner confirmed it is a usable Reality target. */
    private suspend fun chooseTarget(api: PanelApi, requested: String?, log: (String) -> Unit): Pair<String, Boolean> {
        val candidates = requested?.let(::listOf) ?: SniPresets.targets
        if (!api.capabilities.realityScan) return candidates.first() to false
        log("Checking Reality targets: ${candidates.joinToString()}")
        val best = scan(api, candidates, log).firstOrNull { it.feasible }
        val host = best?.hostName()
        return when {
            host != null && (requested == null || host.equals(requested, ignoreCase = true)) -> {
                log("Selected $host (${best.latencyMs} ms)")
                host to true
            }
            requested != null -> requested to false
            else -> candidates.first() to false
        }
    }
}

fun RealityTargetVerdict.hostName(): String? = host.ifBlank { null } ?: target.substringBefore(':').ifBlank { null }
